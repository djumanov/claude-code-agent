// Generates the HyperFrames composition (HTML + GSAP) that wraps the prepped
// recording with an animated intro, a lower-third, and an outro card.
// Audio is muted here on purpose: FFmpeg does the voice/music mix afterwards.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { escapeHtml as e } from "./util.mjs";

const require = createRequire(import.meta.url);

export function buildComposition(cfg, { mainDuration, width = 1920, height = 1080 }) {
  const intro = Number(cfg.intro ?? 3);
  const outro = Number(cfg.outro ?? 4);
  const total = +(intro + mainDuration + outro).toFixed(3);
  const b = { bg: "#0b0b12", ink: "#ffffff", accent: "#7c5cff", font: "Inter", ...cfg.brand };
  const lt = cfg.lowerThird ?? {};
  const ltStart = intro + Number(lt.at ?? 1);
  const ltDur = Number(lt.duration ?? 5);
  const showLT = !!(cfg.speaker?.name) && lt.enabled !== false && ltStart + ltDur <= intro + mainDuration;
  const outStart = intro + mainDuration;
  const credit = cfg.music?.credit ? `Music: ${cfg.music.credit} · Epidemic Sound` : "";
  const fontLink = b.font
    ? `<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=${encodeURIComponent(b.font)}:wght@400;600;800&display=swap" />`
    : "";

  return `<!doctype html>
<!-- Generated by vedit compose. Edit project.json and re-run, or hand-edit and run "vedit render". -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    ${fontLink}
    <script src="assets/gsap.min.js"></script>
    <style>
      :root { --bg: ${e(b.bg)}; --ink: ${e(b.ink)}; --accent: ${e(b.accent)}; --font: "${e(b.font)}", system-ui, sans-serif; }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${width}px; height: ${height}px; overflow: hidden; background: var(--bg); }
      #root { position: relative; width: 100%; height: 100%; font-family: var(--font); color: var(--ink); }
      .card { position: absolute; inset: 0; display: flex; flex-direction: column; align-items: center; justify-content: center; gap: 28px; background: var(--bg); }
      .card .bar { width: 120px; height: 8px; border-radius: 4px; background: var(--accent); }
      .card h1 { font-size: 104px; font-weight: 800; letter-spacing: -0.035em; text-align: center; max-width: 1500px; line-height: 1.02; }
      .card h2 { font-size: 40px; font-weight: 400; opacity: 0.72; text-align: center; max-width: 1300px; }
      #main { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: contain; background: #000; }
      #lt { position: absolute; left: 80px; bottom: 90px; display: flex; align-items: stretch; gap: 22px; padding: 22px 34px 22px 26px; background: rgba(10,10,16,0.82); border-radius: 18px; backdrop-filter: blur(8px); }
      #lt .accent { width: 8px; border-radius: 4px; background: var(--accent); }
      #lt .name { font-size: 44px; font-weight: 800; letter-spacing: -0.02em; }
      #lt .role { font-size: 28px; opacity: 0.75; margin-top: 4px; }
      #outro .cta { margin-top: 12px; padding: 22px 48px; border-radius: 999px; background: var(--accent); font-size: 40px; font-weight: 600; }
      #outro .credit { position: absolute; bottom: 56px; font-size: 24px; opacity: 0.5; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="${width}" data-height="${height}" data-fps="${cfg.fps ?? 30}">
      <video id="main" class="clip" data-start="${intro}" data-duration="${mainDuration}" data-track-index="0" src="assets/main.mp4" muted playsinline></video>
${
  intro > 0
    ? `
      <div id="intro" class="card clip" data-start="0" data-duration="${intro}" data-track-index="1">
        <div class="bar"></div>
        <h1 id="intro-title">${e(cfg.title)}</h1>
        ${cfg.subtitle ? `<h2 id="intro-sub">${e(cfg.subtitle)}</h2>` : ""}
      </div>`
    : ""
}${
  showLT
    ? `
      <div id="lt" class="clip" data-start="${ltStart}" data-duration="${ltDur}" data-track-index="2">
        <div class="accent"></div>
        <div><div class="name">${e(cfg.speaker.name)}</div>${cfg.speaker.role ? `<div class="role">${e(cfg.speaker.role)}</div>` : ""}</div>
      </div>`
    : ""
}${
  outro > 0
    ? `
      <div id="outro" class="card clip" data-start="${outStart}" data-duration="${outro}" data-track-index="3">
        <h1 id="outro-title">${e(cfg.outroTitle || "Thanks for watching")}</h1>
        ${cfg.cta ? `<div class="cta" id="outro-cta">${e(cfg.cta)}</div>` : ""}
        ${credit ? `<div class="credit">${e(credit)}</div>` : ""}
      </div>`
    : ""
}
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
${
  intro > 0
    ? `      tl.from("#intro .bar", { scaleX: 0, transformOrigin: "left center", duration: 0.6, ease: "power3.out" }, 0.1);
      tl.from("#intro-title", { y: 60, opacity: 0, filter: "blur(10px)", duration: 0.8, ease: "power4.out" }, 0.25);
      ${cfg.subtitle ? `tl.from("#intro-sub", { y: 30, opacity: 0, duration: 0.7, ease: "power3.out" }, 0.55);` : ""}
      tl.to("#intro", { opacity: 0, duration: 0.5, ease: "power2.in" }, ${Math.max(0, intro - 0.5)});
`
    : ""
}${
  showLT
    ? `      tl.from("#lt", { x: -60, opacity: 0, duration: 0.6, ease: "power3.out" }, ${ltStart});
      tl.to("#lt", { x: -40, opacity: 0, duration: 0.45, ease: "power2.in" }, ${(ltStart + ltDur - 0.45).toFixed(3)});
`
    : ""
}${
  outro > 0
    ? `      tl.from("#outro", { opacity: 0, duration: 0.6, ease: "power2.out" }, ${outStart});
      tl.from("#outro-title", { y: 40, opacity: 0, duration: 0.7, ease: "power4.out" }, ${outStart + 0.2});
      ${cfg.cta ? `tl.from("#outro-cta", { scale: 0.8, opacity: 0, duration: 0.6, ease: "back.out(2)" }, ${outStart + 0.5});` : ""}
`
    : ""
}      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
`;
}

/** Write a self-contained HyperFrames project into build/hf. */
export function writeHyperframesProject(proj, mainVideo, info) {
  const hf = proj.p("build", "hf");
  fs.mkdirSync(path.join(hf, "assets"), { recursive: true });
  const dest = path.join(hf, "assets", "main.mp4");
  fs.rmSync(dest, { force: true });
  try {
    fs.linkSync(mainVideo, dest); // hard link: no extra disk use
  } catch {
    fs.copyFileSync(mainVideo, dest);
  }
  // Vendor GSAP so renders work offline / behind proxies.
  fs.copyFileSync(require.resolve("gsap/dist/gsap.min.js"), path.join(hf, "assets", "gsap.min.js"));
  fs.writeFileSync(
    path.join(hf, "hyperframes.json"),
    JSON.stringify(
      {
        $schema: "https://hyperframes.heygen.com/schema/hyperframes.json",
        registry: "https://raw.githubusercontent.com/heygen-com/hyperframes/main/registry",
        paths: { blocks: "compositions", components: "compositions/components", assets: "assets" },
        media: { autoProxy: true },
      },
      null,
      2,
    ) + "\n",
  );
  const pkg = path.join(hf, "package.json");
  if (!fs.existsSync(pkg)) fs.writeFileSync(pkg, JSON.stringify({ name: `${proj.name}-hf`, private: true, type: "module" }, null, 2) + "\n");
  const html = buildComposition(proj.cfg, { mainDuration: +info.duration.toFixed(3) });
  fs.writeFileSync(path.join(hf, "index.html"), html);
  return hf;
}
